"""검색 색인용 본문 정제.

Jina Reader는 페이지 전체를 Markdown으로 옮기므로 저장된 본문에 사이트 메뉴·
관련기사 목록·광고가 함께 들어 있다(2026-08-05 실측, 최근 60건 평균 26,730자).
이 상태로 색인하면 관련기사 목록에 낀 단어 하나로 무관한 문서가 검색에 걸린다
— '블록체인' 검색에 방탄소년단 기사가, '프로야구' 검색에 반도체 기사만 나왔다.

원문(markdown)은 인용·표시에 필요하므로 그대로 두고, 검색 색인 대상만 좁힌다.
"""

from agent.assistant.api import clean_article_body

# 검색 색인에 담을 기사 본문 상한.
#
# 실측(2026-08-05, 최근 60건)으로 정했다. 잡음 제거와 신호 보존이 상충한다.
#
#   2,000자   잡음 '블록체인' 5→1건. 그러나 신호도 '전기차' 9→1건으로 죽는다.
#   6,000자   잡음 '블록체인' 5→3건. 신호는 '반도체' 93%·'코스피' 94% 유지.
#
# 임베딩 입력 상한(clean_article_body 기본값 2,000자)과 값이 다른 이유는 용도가
# 다르기 때문이다. 임베딩은 주제만 잡으면 되지만 검색은 본문 뒤쪽 키워드로도
# 걸려야 한다.
#
# 10,000자도 재봤으나 이득이 없어 되돌렸다(2026-08-05). 상한에 걸려 잘리던 주제가
# 살아날 것으로 봤지만 주제 유사도가 그대로였다 — 잘려서 못 찾은 것이 아니라
# 창고에 그 주제 자료가 애초에 없었다.
#
#   주제 유사도   6,000자 → 10,000자
#   반도체        0.477 → 0.477
#   전기차        0.324 → 0.324   (살아나기를 기대했던 케이스)
#   블록체인      0.361 → 0.315
#
# 값이 같다면 색인이 가볍고 잡음 노출이 적은 쪽이 낫다.
SEARCH_BODY_MAX_CHARS = 6000


def build_search_body(markdown: str | None, *, title: str = "") -> str | None:
    """검색 색인에 쓸 기사 본문을 만든다.

    제목을 주면 메뉴 구간을 건너뛰고 본문부터 자른다 — 앞에서부터 자르면 메뉴가
    긴 매체는 본문에 닿기 전에 잘린다(실측: 평균 6,255자가 메뉴였다).

    Args:
        markdown: 수집한 페이지 전체 Markdown
        title: 저장된 기사 제목. 본문 시작점 탐지에 쓴다.

    Returns:
        정제된 본문. 원문이 없거나 정제 결과가 비면 None(호출자가 원문으로
        대체하도록 둔다).
    """
    if not markdown or not markdown.strip():
        return None
    cleaned = clean_article_body(markdown, SEARCH_BODY_MAX_CHARS, title=title)
    return cleaned or None
